/**
 * Intent-exploration matrix generator.
 *
 * Runs the guard's decide() over every task x action combination and
 * writes SCENARIOS.md from the COMPUTED results — the file is generated,
 * not hand-written. Money cells each read the live allowance (view calls
 * only) and never execute a spend.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { decide, clearAuditLog } from '../src/guard.mjs';
import { AGENT_ID, PAYEE_ID, getAllowance, yoctoToNear } from '../src/near.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));

const TASKS = [
  {
    name: 'Summarize Doc A',
    tools: ['readDoc', 'writeDoc', 'deleteDoc', 'spendNear'],
    intent: { verbs: ['read'], resources: ['doc-a'] },
  },
  {
    name: 'Pay the payee 0.1 NEAR',
    tools: ['readDoc', 'writeDoc', 'deleteDoc', 'spendNear'],
    intent: { verbs: ['spend'], resources: [PAYEE_ID] },
  },
  {
    name: 'Summarize Doc A AND pay the payee',
    tools: ['readDoc', 'writeDoc', 'deleteDoc', 'spendNear'],
    intent: { verbs: ['read', 'spend'], resources: ['doc-a', PAYEE_ID] },
  },
];

const ACTIONS = [
  { label: 'Read Doc A', tool: 'readDoc', args: { name: 'doc-a' } },
  { label: 'Read Doc B', tool: 'readDoc', args: { name: 'doc-b' } },
  { label: 'Write Doc A', tool: 'writeDoc', args: { name: 'doc-a', text: 'x' } },
  { label: 'Delete Doc A', tool: 'deleteDoc', args: { name: 'doc-a' } },
  { label: 'Spend 0.01 NEAR to payee', tool: 'spendNear', args: { to: PAYEE_ID, amountNear: '0.01' } },
  { label: 'Spend 0.80 NEAR to payee', tool: 'spendNear', args: { to: PAYEE_ID, amountNear: '0.80' } },
  { label: 'Spend 0.01 NEAR to a stranger', tool: 'spendNear', args: { to: 'stranger.testnet', amountNear: '0.01' } },
];

function esc(s) {
  return String(s).replace(/\|/g, '\\|');
}

async function main() {
  clearAuditLog();
  const allowance = await getAllowance(AGENT_ID);
  const remaining = yoctoToNear(BigInt(allowance.cap) - BigInt(allowance.spent));
  const stateLine =
    `Live allowance at generation time: cap ${yoctoToNear(allowance.cap)} NEAR, ` +
    `spent ${yoctoToNear(allowance.spent)} NEAR, remaining ${remaining} NEAR, ` +
    `revoked=${allowance.revoked}, allowlist=${JSON.stringify(allowance.allowlist)}.`;

  const rows = [];
  for (const task of TASKS) {
    for (const action of ACTIONS) {
      const out = await decide(task, { tool: action.tool, args: action.args });
      rows.push({ task: task.name, action: action.label, decision: out.decision, stage: out.stage, reason: out.reason });
    }
  }

  const lines = [];
  lines.push('# Intent Exploration Matrix');
  lines.push('');
  lines.push('Every cell below is the COMPUTED result of running the guard’s `decide()` on that task x action pair (generated by `demo/matrix.mjs`). Money cells each read the live allowance (view calls only) and never execute a spend.');
  lines.push('');
  lines.push(stateLine);
  lines.push('');
  lines.push('| Task | Action | Decision | Stage | Reason |');
  lines.push('|------|--------|----------|-------|--------|');
  for (const r of rows) {
    lines.push(`| ${esc(r.task)} | ${esc(r.action)} | ${r.decision} | ${r.stage} | ${esc(r.reason)} |`);
  }
  lines.push('');
  lines.push('## Notes on surprising cells');
  lines.push('');
  lines.push('- **Spend 0.80 NEAR** denies at the *money* stage with the live numbers (remaining 0.75 NEAR), and the reason ALSO lists the revoked state — the money pre-check reports every failing check, in the contract’s own order, so the over-cap fact is visible even though the contract itself would hit the revoked check first. The cap-exceeded panic itself is recorded evidence from the 9 Nov e2e run (see README), from when the allowance was still active.');
  lines.push('- **Spend to a stranger** denies at *money* too (not allowlisted) — again alongside the revoked reason, for the same all-failures-reported rule.');
  lines.push('- **Policy never fires in this matrix** because all three tasks list every demo tool. Narrow the task’s tool list and the same actions deny at *policy* instead — that is what the demo’s scene tasks do (read task: only `readDoc`; pay task: only `spendNear`).');
  lines.push('- **The combined task (read + spend)** allows Read Doc A and denies Read Doc B: intent is per-call, so adding a second verb does not widen the first resource’s scope.');
  lines.push('');
  lines.push(`Generated ${new Date().toISOString()} by \`node demo/matrix.mjs\`.`);
  lines.push('');
  writeFileSync(join(HERE, '..', 'SCENARIOS.md'), lines.join('\n'));
  console.log(`SCENARIOS.md written (${rows.length} cells). ${stateLine}`);
}

main().catch((err) => {
  console.error('matrix error:', err);
  process.exit(1);
});
